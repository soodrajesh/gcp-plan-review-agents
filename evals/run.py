"""Cross-provider evaluation. For every sample plan and provider it measures what the model adds
and what it must NOT change.

    GOOGLE_CLOUD_PROJECT=<proj> .venv/bin/python evals/run.py --providers mock,vertex
    .venv/bin/python evals/run.py --providers openai --repeat 1     # reads OPENAI_API_KEY from .env

Invariants checked for every run:
  verdict_stable   verdict equals the rules-only verdict (the model must never move it)
  rules_intact     every rule finding survives (the model must not remove or lower any)
  clean_output     no kept note/summary contains a link
Reported: model-proposed extras kept/dropped, notes attached, degraded runs, cost, latency."""

import argparse
import asyncio
import json
import os
import statistics
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
for line in (ROOT / ".env").read_text().splitlines() if (ROOT / ".env").exists() else []:
    k, _, v = line.partition("=")
    if k and not k.startswith("#") and k != "PLANREVIEW_LLM":
        os.environ.setdefault(k, v)

from planreview.llm import Budget, make_llm  # noqa: E402
from planreview.orchestrator import review_plan  # noqa: E402

SAMPLES = ROOT / "planreview" / "samples"


async def main(providers: list[str], repeat: int, out: Path) -> int:
    rows, bad = [], 0
    for name in sorted(p.stem for p in SAMPLES.glob("*.json")):
        doc = json.loads((SAMPLES / f"{name}.json").read_text())
        base = await review_plan(doc, make_llm("none"))
        base_rules = Counter((f.rule, f.address, f.severity, f.title) for f in base.findings)
        for prov in providers:
            for _ in range(repeat):
                r = await review_plan(
                    doc, make_llm(prov), budget=Budget(max_calls=6, max_cost_usd=0.05)
                )
                got = Counter(
                    (f.rule, f.address, f.severity, f.title)
                    for f in r.findings
                    if f.source == "rule"
                )
                extras = [f for f in r.findings if f.source == "llm"]
                text = " ".join([r.summary] + [f.context + f.title for f in r.findings]).lower()
                row = {
                    "plan": name,
                    "provider": f"{r.provider}/{r.model}",
                    "verdict": r.verdict,
                    "verdict_stable": r.verdict == base.verdict,
                    "rules_intact": got == base_rules,
                    "clean_output": "http" not in text and "www." not in text,
                    "notes": sum(1 for f in r.findings if f.context and f.source == "rule"),
                    "rule_findings": sum(got.values()),
                    "extras_kept": len(extras),
                    "dropped": len(r.dropped),
                    "degraded": len(r.degraded),
                    "cost_usd": r.cost_usd,
                    "ms": r.duration_ms,
                }
                bad += not (row["verdict_stable"] and row["rules_intact"] and row["clean_output"])
                rows.append(row)
                print(
                    row["plan"],
                    row["provider"],
                    row["verdict"],
                    "ok" if not bad else "VIOLATION",
                    flush=True,
                )

    lines = [
        "# Evaluation results",
        "",
        "Generated by `evals/run.py`. Invariants must hold on every run; the other columns are what the model adds.",
        "",
        "| plan | provider | verdict | stable | rules intact | clean | notes | extras kept | dropped by critic | degraded | cost | ms |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['plan']} | {r['provider']} | {r['verdict']} | {'✓' if r['verdict_stable'] else '✗'} | "
            f"{'✓' if r['rules_intact'] else '✗'} | {'✓' if r['clean_output'] else '✗'} | {r['notes']}/{r['rule_findings']} | "
            f"{r['extras_kept']} | {r['dropped']} | {r['degraded']} | ${r['cost_usd']:.4f} | {r['ms']} |"
        )
    by = {}
    for r in rows:
        by.setdefault(r["provider"], []).append(r)
    lines += [
        "",
        "## Per provider",
        "",
        "| provider | runs | invariant violations | total dropped by critic | extras kept | total cost | median ms |",
        "|---|---|---|---|---|---|---|",
    ]
    for p, rs in by.items():
        v = sum(not (x["verdict_stable"] and x["rules_intact"] and x["clean_output"]) for x in rs)
        lines.append(
            f"| {p} | {len(rs)} | {v} | {sum(x['dropped'] for x in rs)} | {sum(x['extras_kept'] for x in rs)} | "
            f"${sum(x['cost_usd'] for x in rs):.4f} | {int(statistics.median(x['ms'] for x in rs))} |"
        )
    out.write_text("\n".join(lines) + "\n")
    print(f"\nwrote {out}; invariant violations: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--providers", default="mock")
    ap.add_argument("--repeat", type=int, default=1)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "eval-results.md")
    a = ap.parse_args()
    sys.exit(asyncio.run(main(a.providers.split(","), a.repeat, a.out)))
